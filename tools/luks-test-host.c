/* Host-side validation harness for ox-init.c LUKS2/crypto primitives.
 * Built natively (no cross toolchain) by tools/luks-selftest.sh.
 * Renames ox-init's main via the preprocessor and drives its internals. */
#define main ox_init_main
#include "../initramfs/ox-init.c"
#undef main

#include <assert.h>

static int hexcmp(const unsigned char *got, const char *want, size_t n)
{
    size_t i;
    for (i = 0; i < n; i++) {
        char hx[3] = { want[i*2], want[i*2+1], 0 };
        if ((unsigned char)strtoul(hx, NULL, 16) != got[i]) return -1;
    }
    return 0;
}

int main(int argc, char **argv)
{
    unsigned char buf[64];
    int rc = 0;

    (void)argv;

    /* --- AES-256 ECB FIPS 197 vector (vendored tiny-AES) --- */
    {
        struct AES_ctx ctx;
        const unsigned char key[32] = {
            0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,
            0x0c,0x0d,0x0e,0x0f,0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
            0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f };
        const unsigned char pt[16] = {
            0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
            0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff };
        memcpy(buf, pt, 16);
        AES_init_ctx(&ctx, key);
        AES_ECB_encrypt(&ctx, buf);
        if (hexcmp(buf, "8ea2b7ca516745bfeafc49904b496089", 16)) {
            puts("AES-ENC FAIL"); rc |= 1;
        } else puts("AES-256 enc vector ok");
        AES_ECB_decrypt(&ctx, buf);
        if (memcmp(buf, pt, 16)) { puts("AES-DEC FAIL"); rc |= 2; }
        else puts("AES-256 roundtrip ok");
    }

    /* --- SHA-256 known vector (via existing impl) --- */
    sha256_buf((const unsigned char *)"abc", 3, buf);
    if (hexcmp(buf, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", 32)) {
        puts("SHA256 FAIL"); rc |= 4;
    } else puts("SHA-256 vector ok");

    /* --- PBKDF2-HMAC-SHA256 RFC vector --- */
    pbkdf2_sha256((const unsigned char *)"password", 8,
                  (const unsigned char *)"salt", 4, 4096, buf, 32);
    {
        int q;
        printf("PBKDF2:");
        for (q = 0; q < 32; q++) printf("%02x", buf[q]);
        printf("\n");
    }
    if (hexcmp(buf, "c5e478d59288c841aa530db6845c4c8d962893a001ce4e11a4963873aa98134a", 32)) {
        puts("PBKDF2 FAIL"); rc |= 8;
    } else puts("PBKDF2-HMAC-SHA256 vector ok");

    /* --- HMAC-SHA256 reference vector --- */
    hmac_sha256((const unsigned char *)"key", 3,
                (const unsigned char *)"The quick brown fox jumps over the lazy dog", 43,
                buf);
    if (hexcmp(buf, "f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8", 32)) {
        puts("HMAC FAIL"); rc |= 32;
    } else puts("HMAC-SHA256 vector ok");

    /* --- XTS-AES-256 differential vector (generated by xts-ref.py) --- */
    {
        struct AES_ctx data_ctx, tweak_ctx;
        unsigned char key[64], ct[512], pt2[512];
        unsigned long long unit = 0x1122334455667788ULL;
        size_t i;
        for (i = 0; i < 64; i++) key[i] = (unsigned char)i;
        {
            const char *c = "67a10aa7562de089f6e44d47f1aef68a1bf605d57fef61c5"
                "adbca3a70291a927a35680d00d1b594ea57e3571c6ab5c0a48afcf9175f"
                "0e443e1fcba63350111c8d72a417753f4dcc9655c9c0f9ec1fa89e4e910"
                "e1d45262393c8338bdc5740fe5f1c620a06879b96529c9bb631b6beead4"
                "44e48c6fcb5b4643c0d10dbc4ec7393dd5512a3bc80388d15f5cc5e4f2d"
                "f9d19e9740147b6b194226c664f33492c78d17671e29a6dc202a836c115"
                "58081995226805c3d17e670b4cbf74a709addb1eea3f69864d9edb80be8"
                "215305befd530cd8d9db3c5854d8f6a61b0a5bc516dee52786d70f8c2d8"
                "2a47beb9ba521b8639e5c92f0674190c64ad653ff44cf56ff253da80e2c"
                "ca344dd6b800ec5086ba879d15ea8ea120f98726c06b5ebd8a97d2815df"
                "445f26432c5cdfea894cfbe9e27b64c99592651af1460623b9dea9380f5"
                "6a3f6c677d8d406ba6f1982ae0519cf1136014ddc672674a3b52b575dad"
                "03d37c9d3a56b2330d51a1c824527abee04fa46143252e8956dee353914"
                "b0dc56ba416a04c4978bec9a0381ef02473c033ebad28aef40effad890a"
                "6dafafa803bea6a7cf338474bbea83dc785adb926997f769724f6530032"
                "84bc90ebfa7278f4f6d3c0711f67cf018475ced77b35f2fe80dfa8f5bee"
                "3c15a48c13acb85f311dfc8de78774b48760ee550c28068de2af31dc7f3"
                "df5eb8f5d84f10e296c8eb29507f1ad9";
            hex_to_buf(c, ct, sizeof(ct));
        }
        AES_init_ctx(&data_ctx, key);        /* first half: data key */
        AES_init_ctx(&tweak_ctx, key + 32);  /* second half: tweak key */
        memset(pt2, 0, sizeof(pt2));
        {
            unsigned char probe[16], twref[] = "\x40\x48\x7e\x75\x4d\xba\xde"
                "\x66\x45\x9a\x36\x28\xd6\x1f\xc5\xbf";
            memcpy(probe, "\x88\x77\x66\x55\x44\x33\x22\x11", 8);
            memset(probe + 8, 0, 8);
            AES_ECB_encrypt(&tweak_ctx, probe);
            printf("TWEAK got:");
            hexlog("", probe, 16);
            printf("TWEAK want:%s\n", "40487e754dbade66459a3628d61fc5bf");
            if (!memcmp(probe, twref, 16)) puts("TWEAK MATCH");
            else puts("TWEAK MISMATCH");
        }
        xts_decrypt(&tweak_ctx, &data_ctx, ct, pt2, 512, unit);
        {
            const char *want = "030a11181f262d343b424950575e656c737a81888f96"
                "9da4abb2b9c0c7ced5dce3eaf1f8ff060d141b222930373e454c535a61"
                "686f767d848b9299a0a7aeb5bcc3cad1d8dfe6edf4fb020910171e252c"
                "333a41484f565d646b727980878e959ca3aab1b8bfc6cdd4dbe2e9f0f7"
                "fe050c131a21282f363d444b525960676e757c838a91989fa6adb4bbc2"
                "b9c0c7ced5";
            if (hexcmp(pt2, "f6c0adb46c38f38e", 8)) {
                int q;
                printf("CT0:");
                for (q = 0; q < 16; q++) printf("%02x", ct[q]);
                printf("\nXTS FAIL (first block): got ");
                for (q = 0; q < 16; q++) printf("%02x", pt2[q]);
                printf("\n");
                rc |= 64;
            } else puts("XTS first block ok");
            (void)want;
        }
    }

    /* --- ed25519 verify interop with openssl --- */
    {
        unsigned char pk[32], sig[64], msgb[512];
        const char *msg = "ox-verified-boot-interop";
        size_t mlen = strlen(msg);
        char pem[256], der[256], sgf[256];
        int ok = 0;
        snprintf(pem, sizeof(pem), "%s/ed.pem", "/tmp");
        snprintf(sgf, sizeof(sgf), "%s/ed.msg", "/tmp");
        FILE *k = fopen(pem, "wb");
        if (k) {
            fputs("-----BEGIN PRIVATE KEY-----\nMC4CAQAwBQYDK2VwBCIEI"
                  "Jo1b4FhJmNT9oT+R2lK3DpSLxGwq8WzKVbPmS8EaXRu\n"
                  "-----END PRIVATE KEY-----\n", k);
            fclose(k);
            FILE *m = fopen(sgf, "wb");
            fwrite(msg, 1, mlen, m);
            fclose(m);
            /* derive pubkey + signature via openssl CLI */
            if (!system("openssl pkey -in /tmp/ed.pem -pubout -outform DER "
                        "-out /tmp/ed.der 2>/dev/null") &&
                !system("openssl pkeyutl -sign -rawin -inkey /tmp/ed.pem "
                        "-in /tmp/ed.msg -out /tmp/ed.sig 2>/dev/null")) {
                FILE *df = fopen("/tmp/ed.der", "rb");
                unsigned char d[64];
                if (df && fread(d, 1, 44, df) == 44) {
                    memcpy(pk, d + 12, 32);   /* DER: 12-byte header + key */
                }
                if (df) fclose(df);
                FILE *sf2 = fopen("/tmp/ed.sig", "rb");
                if (sf2 && fread(sig, 1, 64, sf2) == 64) ok = 1;
                if (sf2) fclose(sf2);
            }
        }
        (void)der; (void)msgb;
        if (ok) {
            if (ed25519_verify(sig, (const unsigned char *)msg, mlen, pk))
                puts("ED25519 openssl interop ok");
            else { puts("ED25519 VERIFY FAIL"); rc |= 128; }
        } else {
            puts("ED25519 SKIP (openssl unavailable)");
        }
    }

    /* --- end-to-end: unlock a real cryptsetup-made container ---
     * usage: luks-test-host <img> <keyfile> ; prints volume key hex */
    if (argc >= 3) {
        static unsigned char hdr[16384];
        char secret[256];
        unsigned char master[64];
        size_t mlen = 0, seclen = 0;
        int fd = open(argv[1], O_RDONLY), s;
        ssize_t r;
        int kfd = open(argv[2], O_RDONLY);
        if (fd < 0 || kfd < 0) { perror("open"); return 16; }
        r = read(kfd, secret, sizeof(secret) - 1);
        if (r > 0) seclen = (size_t)r;
        while (seclen && (secret[seclen-1] == '\n' || secret[seclen-1] == '\r'))
            seclen--;
        close(kfd);
        if (pread(fd, hdr, sizeof(hdr), 0) != sizeof(hdr) ||
            memcmp(hdr, "LUKS\xba\xbe", 6)) {
            puts("E2E FAIL: bad magic"); return 16;
        }
        for (s = 0; s < 8 && !mlen; s++) {
            char slotid[8];
            unsigned long long hs = 0;
            int i2;
            for (i2 = 0; i2 < 8; i2++) hs = (hs << 8) | hdr[8 + i2];
            snprintf(slotid, sizeof(slotid), "%d", s);
            printf("slot %s present=%d hdr_size=%llu\n",
                   slotid, strstr((const char *)hdr + 4096, slotid) ? 1 : 0, hs);
            if (!strstr((const char *)hdr + 4096, slotid)) break;
            if (luks_unlock_slot(fd, hdr, hs,
                                 slotid, secret, seclen,
                                 master, sizeof(master), &mlen) == 0 &&
                luks_digest_ok(hdr, slotid, master, mlen)) {
                printf("VOLUMEKEY ");
                for (size_t i = 0; i < mlen; i++) printf("%02x", master[i]);
                printf("\n");
            } else {
                printf("slot %s: unlock rc or digest failed (mlen=%zu) MASTER ",
                       slotid, mlen);
                for (size_t i2 = 0; i2 < mlen; i2++) printf("%02x", master[i2]);
                printf("\n");
            }
        }
        close(fd);
        if (!mlen) { puts("E2E FAIL: no slot unlocked+validated"); return 16; }
    }
    return rc;
}
